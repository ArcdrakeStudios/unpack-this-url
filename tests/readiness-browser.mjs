import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = process.env.PLAYWRIGHT_MODULE ? await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href) : require('playwright');
const root = new URL('../', import.meta.url);
const results = [];
let browser;
const server = spawn(process.execPath, ['tools/serve.mjs'], { cwd: root, stdio: ['ignore','pipe','pipe'], windowsHide: true });
try {
 await new Promise((resolve,reject) => { const timer=setTimeout(()=>reject(Error('Preview startup timed out')),10000); server.stdout.once('data',()=>{clearTimeout(timer);resolve();}); server.once('error',reject); server.once('exit',code=>reject(Error('Preview exited '+code))); });
 browser=await chromium.launch({headless:true});
 await mkdir(new URL('../artifacts/readiness/',import.meta.url),{recursive:true});
 const screenshotFolder=process.env.UPDATE_SCREENSHOTS==='1'?'../docs/':'../artifacts/readiness/';
 await mkdir(new URL(screenshotFolder,import.meta.url),{recursive:true});
 const context=await browser.newContext({viewport:{width:1280,height:900}, permissions:['clipboard-read','clipboard-write']});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const requests=[];page.on('request',r=>requests.push(r.url()));
 await page.goto('http://127.0.0.1:43218');
 await page.locator('#example').click();
 for(const id of ['remove-tracking','remove-credentials','remove-fragment']) await page.locator('#'+id).check();
 const expected='https://xn--bcher-kva.example:8443/read?tag=one&tag=two&next=https%3A%2F%2Fexample.org%2Fwelcome%3Fx%3D1';
 assert.equal(await page.locator('#preview').inputValue(),expected);
 await page.locator('#copy').click();
 assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),expected);
 results.push('Actual Chromium clipboard read equals exact transformed preview');
 assert.equal(await page.locator('a').count(),1);assert(requests.every(u=>u.startsWith('http://127.0.0.1:43218/')));
 results.push('Submitted URLs remain inert; only local page/assets requested');
 await page.screenshot({path:fileURLToPath(new URL(screenshotFolder+'screenshot-desktop.png',import.meta.url)),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:fileURLToPath(new URL(screenshotFolder+'screenshot-mobile.png',import.meta.url)),fullPage:true});results.push('390px layout has no horizontal overflow');
 await page.locator('#clear').click();assert.equal(await page.locator('#url-input').inputValue(),'');assert(await page.locator('#results').isHidden());results.push('Clear removes input and results');
 await context.clearPermissions();
 await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:()=>Promise.reject(Error('denied'))},configurable:true}));
 await page.locator('#example').click();await page.locator('#remove-tracking').check();await page.locator('#copy').click();
 await page.waitForFunction(()=>document.querySelector('#copy-status').textContent.includes('unavailable'));
 assert(await page.locator('#preview').evaluate(e=>e.selectionStart===0&&e.selectionEnd===e.value.length));results.push('Injected clipboard denial selects full manual-copy preview');
 assert.deepEqual(errors,[]);results.push('No uncaught page errors');
 await writeFile(new URL('../artifacts/readiness/browser.json',import.meta.url),JSON.stringify({browser:browser.version(),date:new Date().toISOString(),checks:results,limits:'Chromium headless clipboard; physical device and OS clipboard UI untested. Clipboard denial is injected.'},null,2));
 console.log(JSON.stringify({checks:results,browser:browser.version()},null,2));
} finally { if(browser)await browser.close(); server.kill(); await new Promise(resolve=>server.exitCode!==null?resolve():server.once('exit',resolve)); }
